-- ---------------------------------------------------------------------------
-- 1. TABLES CREATION
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS curriculums (
    curriculum_id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    year INTEGER NOT NULL,
    total_credits_target INTEGER,
    max_credits_per_semester INTEGER
);

CREATE TABLE IF NOT EXISTS curriculum_categories (
    curriculum_id VARCHAR(50) NOT NULL,
    category_name VARCHAR(50) NOT NULL,
    required_credits INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (curriculum_id, category_name),
    FOREIGN KEY (curriculum_id) REFERENCES curriculums(curriculum_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS courses (
    course_code VARCHAR(20) PRIMARY KEY,
    course_name_th VARCHAR(255) NOT NULL,
    course_name_en VARCHAR(255) NOT NULL,
    credit_str VARCHAR(20),
    credit INTEGER NOT NULL DEFAULT 0,
    url VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS curriculum_courses (
    curriculum_id VARCHAR(50) NOT NULL,
    course_code VARCHAR(20) NOT NULL,
    year INTEGER,
    semester INTEGER,
    plan_type VARCHAR(100),
    category VARCHAR(50),
    PRIMARY KEY (curriculum_id, course_code),
    FOREIGN KEY (curriculum_id) REFERENCES curriculums(curriculum_id) ON DELETE CASCADE,
    FOREIGN KEY (course_code) REFERENCES courses(course_code) ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS prerequisites (
    course_code VARCHAR(20) NOT NULL,
    prereq_code VARCHAR(20) NOT NULL,
    PRIMARY KEY (course_code, prereq_code),
    FOREIGN KEY (course_code) REFERENCES courses(course_code) ON DELETE CASCADE,
    FOREIGN KEY (prereq_code) REFERENCES courses(course_code) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS advisors (
    advisor_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    cohort_year INTEGER
);

CREATE TABLE IF NOT EXISTS advisor_credentials (
    advisor_id VARCHAR(20) PRIMARY KEY,
    password_hash VARCHAR(128) NOT NULL,
    FOREIGN KEY (advisor_id) REFERENCES advisors(advisor_id)
);

CREATE TABLE IF NOT EXISTS students (
    student_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    admission_year INTEGER,
    advisor_id VARCHAR(20),
    curriculum_id VARCHAR(50),
    transcript_filename VARCHAR(255),
    last_uploaded_at TIMESTAMP,
    FOREIGN KEY (advisor_id) REFERENCES advisors(advisor_id),
    FOREIGN KEY (curriculum_id) REFERENCES curriculums(curriculum_id)
);

CREATE TABLE IF NOT EXISTS transcript_courses (
    id SERIAL PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL,
    course_code VARCHAR(20) NOT NULL,
    course_name_raw VARCHAR(255) NOT NULL,
    credit INTEGER NOT NULL,
    grade VARCHAR(10),
    semester INTEGER,
    academic_year VARCHAR(20),
    is_overridden BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (student_id) REFERENCES students(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_code) REFERENCES courses(course_code)
);




